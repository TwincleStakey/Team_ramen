# -*- coding: utf-8 -*-
"""화면 가장자리를 누르는 비네트 그림을 굽는다.

## 왜 후처리가 아니라 그림인가

처음에는 URP Volume 의 Vignette 로 넣었다. 카메라 후처리라 화면에 그려진 것을 다 덮는데,
**그게 문제였다** — 이 게임은 배경·손님·그릇뿐 아니라 상단바·키 힌트·팝업까지 전부 UI 라
UI 도 같이 눌린다. 세기 0.5 에서는 상단바 오른쪽과 키 힌트가 **완전히 검정**이 됐다.

세기를 낮추면 비네트가 안 보이고, 올리면 UI 가 죽는다. 둘 다 만족하려면 **UI 가 비네트 위에
그려져야** 하고, 그건 후처리로는 못 한다 — 다 그린 뒤에 먹이니까.

그림으로 내리면 정렬 순서로 그 층을 고를 수 있다(빌더의 `VignetteOrder` = 182).

## 모양

URP Vignette 셰이더의 식을 그대로 옮겼다.

    d = |uv − 0.5| × (intensity×3)      (가로는 화면 비를 곱한다)
    d = saturate(d) ^ (smoothness×5)
    밝기 = saturate(1 − dot(d, d))

여기서는 그 「밝기」의 반대만큼 어두운 색을 덮는다. 유니티에서 이미지 알파를 낮추면
더 옅게 쓸 수 있다 — 조리 화면이 그렇게 쓴다.

## 크기

480x270 이면 충분하다. 매끈한 그라데이션이라 늘려도 계단이 안 진다.

**판(Frame) 에 딱 맞춰 늘려야 한다.** 처음에 화면 덮개 크기(1920x1080 캔버스 단위)로 깔았더니
화면에 보이는 것은 960x540 이라 **그라데이션의 안쪽 절반만 보였다** — 세기를 아무리 올려도
옅게만 깔린다. 합성 시안으로는 못 잡고 실제로 찍어 보고 알았다.

## 세기 고르기

`INTENSITY` 를 바꿔 다시 구우면 된다. 실제 식으로 계산한 자리별 밝기(1 이면 원본):

| intensity | 구석 | 좌우 끝 | 위아래 끝 |
|---|---|---|---|
| 0.20 | 0.94 | 0.94 | 1.00 |
| 0.28 | 0.71 | 0.73 | 0.98 |
| **0.34** | **0.31** | **0.36** | 0.95 |
| 0.40 | 0.00 | 0.00 | 0.90 |
| 0.50 | 0.00 | 0.00 | 0.73 |

**0.40 부터는 구석이 완전히 검정이다.** 쓸 구간이 0.28~0.36 으로 좁다.
0.50 으로 넣었다가 사용자가 실제 화면을 보고 세다고 해서 0.34 로 내렸다.

가로가 세로보다 훨씬 많이 눌린다(0.34 에서 좌우 끝 0.36 vs 위아래 끝 0.95). 화면 비를
곱하기 때문이다. 상단바가 위쪽 가운데에 있어서 덜 눌리는 것도 이 덕이다.

(예전 주석에 「0.34 면 구석이 0.97」이라고 적어 둔 표가 있었는데 **틀린 계산이었다** —
가로에 화면 비를 곱하는 것을 빼먹었다. 위 표가 맞다.)
"""
import os
import sys

from PIL import Image

OUT = sys.argv[1] if len(sys.argv) > 1 else 'Assets/Art/UI/Generated/비네트.png'

W, H = 480, 270
INTENSITY = 0.34                    # 주문 화면 기준. 그보다 옅게 쓸 때는 유니티에서 알파를 낮춘다
SMOOTHNESS = 0.45

# 순수 검정이 아니라 **살짝 붉은 검정**이다. 검정으로 누르면 가장자리가 잿빛으로 죽는데,
# 배경이 노렌(빨강)·나무(주황)라 그 색이 회색으로 빠지면 싸늘해 보인다.
COLOR = (14, 6, 4)


def main():
    img = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    px = img.load()

    ie = INTENSITY * 3.0
    se = SMOOTHNESS * 5.0
    aspect = W / float(H)

    for y in range(H):
        dy = min(1.0, abs(y / (H - 1.0) - 0.5) * ie) ** se
        for x in range(W):
            dx = min(1.0, abs(x / (W - 1.0) - 0.5) * ie * aspect) ** se
            bright = max(0.0, 1.0 - (dx * dx + dy * dy))
            px[x, y] = (COLOR[0], COLOR[1], COLOR[2], int(round((1.0 - bright) * 255)))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    img.save(OUT)

    print('%s  %dx%d  intensity %.2f   구석 %.2f / 좌우끝 %.2f / 위아래끝 %.2f'
          % (OUT, W, H, INTENSITY,
             1 - px[0, 0][3] / 255.0,
             1 - px[0, H // 2][3] / 255.0,
             1 - px[W // 2, 0][3] / 255.0))


if __name__ == '__main__':
    main()
